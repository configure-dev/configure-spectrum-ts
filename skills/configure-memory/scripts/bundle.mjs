#!/usr/bin/env node
// Bundles the skill into a single self-contained installer script that can be
// hosted (docs.configure.dev/skill/install.mjs) and run with:
//   curl -fsSL <url> | node -
// Usage: node scripts/bundle.mjs <output-path>
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INCLUDE = [
  "SKILL.md",
  "README.md",
  "install.mjs",
  "engine/credentials.mjs",
  "engine/mcp-client.mjs",
  "engine/digest.mjs",
  "hooks/session-start.mjs",
  "formats/AGENTS-block.md",
];

const files = {};
for (const rel of INCLUDE) files[rel] = readFileSync(join(ROOT, rel), "utf8");

const out = `#!/usr/bin/env node
// configure-memory skill installer (generated by scripts/bundle.mjs — do not edit)
// CJS bootstrap so "curl ... | node -" works on Node >= 18 (stdin is CJS;
// an ESM stdin script would SyntaxError on Node < 22.7). Writes the skill to
// ~/.claude/skills/configure-memory and registers the read-only SessionStart
// digest hook in ~/.claude/settings.json.
"use strict";
const major = Number(process.versions.node.split(".")[0]);
if (major < 18) {
  console.error("configure-memory installer needs Node 18+ (found " + process.version + ")");
  process.exit(1);
}
const { writeFileSync, mkdirSync, rmSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, dirname } = require("node:path");
const { pathToFileURL } = require("node:url");

const FILES = ${JSON.stringify(files)};

const stage = join(tmpdir(), "configure-memory-" + process.pid);
for (const [rel, content] of Object.entries(FILES)) {
  const p = join(stage, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
}
import(pathToFileURL(join(stage, "install.mjs")).href)
  .then(({ install }) => {
    const { dest } = install({});
    console.log("configure-memory installed at " + dest);
    console.log("SessionStart digest hook registered. Open a new Claude Code session to see it.");
  })
  .catch((e) => {
    console.error("install failed: " + e.message);
    process.exitCode = 1;
  })
  .finally(() => {
    try { rmSync(stage, { recursive: true, force: true }); } catch {}
  });
`;

const target = process.argv[2];
if (!target) {
  console.error("usage: node scripts/bundle.mjs <output-path>");
  process.exit(1);
}
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`bundled ${Object.keys(files).length} files -> ${target}`);
