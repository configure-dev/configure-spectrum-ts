#!/usr/bin/env node
// Bundles the skill into a single self-contained installer script that can be
// hosted (docs.configure.dev/skill/install.mjs) and run with:
//   curl -fsSL <url> | node -
// Usage: node scripts/bundle.mjs <output-path>
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INCLUDE = [
  "SKILL.md",
  "README.md",
  "install.mjs",
  "engine/credentials.mjs",
  "engine/mcp-client.mjs",
  "engine/digest.mjs",
  "hooks/session-start.mjs",
  "formats/AGENTS-block.md",
];

const files = {};
for (const rel of INCLUDE) files[rel] = readFileSync(join(ROOT, rel), "utf8");

const out = `#!/usr/bin/env node
// configure-memory skill installer (generated by scripts/bundle.mjs — do not edit)
// Polyglot bootstrap: runs piped ("curl ... | node -", where stdin is CJS on
// Node < 22.7) AND as a downloaded file ("node install.mjs", parsed as ESM).
// Only dynamic import(), no require, no top-level await — valid in both.
// Writes the skill to ~/.claude/skills/configure-memory and registers the
// read-only SessionStart digest hook in ~/.claude/settings.json.
"use strict";
const major = Number(process.versions.node.split(".")[0]);
if (major < 18) {
  console.error("configure-memory installer needs Node 18+ (found " + process.version + ")");
  process.exit(1);
}

const FILES = ${JSON.stringify(files)};

Promise.all([import("node:fs"), import("node:os"), import("node:path"), import("node:url")])
  .then(([fs, os, path, url]) => {
    // mkdtempSync: unpredictable stage dir, so another local user cannot
    // pre-create the path and win a write/import race.
    const stage = fs.mkdtempSync(path.join(os.tmpdir(), "configure-memory-"));
    for (const [rel, content] of Object.entries(FILES)) {
      const p = path.join(stage, rel);
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, content);
    }
    return import(url.pathToFileURL(path.join(stage, "install.mjs")).href)
      .then(({ install }) => {
        const { dest } = install({});
        console.log("configure-memory installed at " + dest);
        console.log("SessionStart digest hook registered. Open a new Claude Code session to see it.");
      })
      .finally(() => {
        try { fs.rmSync(stage, { recursive: true, force: true }); } catch {}
      });
  })
  .catch((e) => {
    console.error("install failed: " + e.message);
    process.exitCode = 1;
  });
`;

const target = process.argv[2];
if (!target) {
  console.error("usage: node scripts/bundle.mjs <output-path>");
  process.exit(1);
}
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`bundled ${Object.keys(files).length} files -> ${target}`);
